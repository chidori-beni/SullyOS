export const formatLive2DParameterText = (locale: UiLocale, text: string): string =>
  locale === 'ja-JP' ? LIVE2D_PARAMETER_JA[text] ?? text : text;

// Build a display copy; model-specific IDs and semantic classification remain intact.
export const describeLocalizedLive2DParameter = (id: string, locale: UiLocale): Live2DParameterSemantics => {
  const source = describeLive2DParameter(id);
  const display = (text: string) => formatLive2DParameterText(locale, text);
  return {
    ...source,
    areaLabel: display(source.areaLabel),
    label: source.area === 'other' && id.trim() ? source.label : display(source.label),
    description: display(source.description),
    negativeLabel: display(source.negativeLabel),
    positiveLabel: display(source.positiveLabel),
  };
};
