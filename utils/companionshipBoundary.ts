/**
 * 「陪伴，不监督」边界 —— 聊天与通话**共用同一份文案**。
 *
 * ## 这条边界是干嘛的
 *
 * 一句话：**别把角色写成催你写作业的家长。**
 *
 * 你随口说一句「我在洗漱」「等下要睡了」，多数时候只是在分享近况，
 * 不是把待办交给对方管理。但模型很容易顺着「关心」滑向「监督」：
 * 追问做完没有、倒计时、每段话收尾都挂一句提醒。
 *
 * ## 为什么必须是共用的一份
 *
 * 原先它**只写在 `apps/CallApp.tsx` 里、且无条件生效**，
 * 而 `utils/chatPrompts.companionship.test.ts` 早就写好了「聊天里也该有」的测试 ——
 * 源码那半却一直没落地（查过全部 git 历史：`chatPrompts.ts` 从来没有过这段文字）。
 *
 * 修的时候如果两边各抄一份，迟早会漂：改了通话忘了聊天，
 * 用户就会遇到「我在聊天里关了，打电话过来还是催我」。所以抽到这里，两边都引这一份。
 *
 * ## ⛔ 两处口径必须不同，别合并成一句
 *
 * 「这条边界在**本通电话**后续持续有效」 vs 「在**本次对话**后续持续有效」。
 * 在聊天里说「本通电话」会让角色以为正在打电话 —— 所以 `scope` 是必填的。
 */

export type CompanionshipScope = 'chat' | 'call';

/** 小标题。测试与调用方都引这一个常量，免得两边各写一遍标题文字。 */
export const COMPANIONSHIP_HEADING = '### 陪伴，不监督（高优先级边界）';

/**
 * 角色是否启用这条边界。
 *
 * **缺省开**（`undefined` 视为 true）—— 用户 2026-09-16 选定。
 * 这保住了通话的现有行为（原本就是无条件生效的）；
 * 代价是所有现有角色的**聊天**里会多出这条边界，用户已知悉并接受。
 *
 * 想要一个会唠叨的角色（妈妈 / 教练 / 担心你身体的恋人）就把它关掉。
 */
export const companionshipBoundaryOn = (
    char?: { companionshipBoundaryEnabled?: boolean } | null,
): boolean => char?.companionshipBoundaryEnabled !== false;

/**
 * 生成这条边界的提示词。关掉（或没启用）时返回空串 —— 调用方直接拼接即可。
 *
 * @param scope `chat` = 普通聊天 / `call` = 通话。只影响「本次对话」与「本通电话」那一处措辞。
 */
export function buildCompanionshipBoundary(
    scope: CompanionshipScope,
    enabled = true,
): string {
    if (!enabled) return '';
    // 「说了别催之后，这条边界持续到什么时候」—— 聊天和通话的自然说法不一样。
    const persistScope = scope === 'call' ? '本通电话' : '本次对话';
    return [
        COMPANIONSHIP_HEADING,
        '',
        '对方提到正在吃饭、洗漱、戴牙套、准备睡觉或之后要做什么，通常是在分享近况，不是在把进度交给你管理。',
        '- 可以关心、陪着聊或自然回应一次，但不要催快点、追问做完没有、倒计时、布置下一步，也不要把每段话收尾成提醒或命令。',
        '- 同一件生活小事不要换个说法反复叮嘱。关心不等于监督，更不等于管教。',
        `- 如果对方说“别催”“不要管我”“别说教”或表达类似边界，这条边界在${persistScope}后续持续有效。简短认错后真正停止，不要嘴上答应、下一句结尾又重复催促。`,
        // ⛔ 这一条是「例外」，别删：用户明确要求提醒时得能提醒，
        //    否则这条边界会反过来变成「角色拒绝帮忙」，那是另一种失败。
        '- 只有对方明确要求你提醒、督促或帮忙安排时，才可以那样做；照办即可，但不把一次授权扩展成长期监督，也不反复催促。',
        '- 想表达在意时，优先用陪伴、共情、分享自己的反应或顺着话题聊天，而不是指挥对方立刻行动。',
    ].join('\n');
}
