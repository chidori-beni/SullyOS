export const formatBookCinemaText = (locale: UiLocale, text: string, ...values: Array<string | number | undefined | null>): string => {
  const key = text.trim();
  const translated = locale === 'ja-JP' && Object.prototype.hasOwnProperty.call(BOOK_CINEMA_JA, key) ? BOOK_CINEMA_JA[key] : key;
  const start = text.indexOf(key);
  const template = start < 0 ? text : text.slice(0, start) + translated + text.slice(start + key.length);
  return template.replace(/\{(\d+)\}/g, (full, index: string) => Number(index) < values.length ? String(values[Number(index)] ?? '') : full);
};
export const useBookCinemaText = () => {
  const { locale } = useUiLocale();
  const current = useRef(locale);
  current.current = locale;
  return useCallback((text: string, ...values: Array<string | number | undefined | null>) => formatBookCinemaText(current.current, text, ...values), []);
};

export const describeCinemaUiStatus = (status: CinemaStatus | null | undefined, t: (text: string, ...values: Array<string | number | undefined | null>) => string): string => {
  if (!status) return '';
  const time = formatVideoTime(status.time);
  if ((status.mode === 'local' || status.mode === 'site') && time) {
    const duration = formatVideoTime(status.duration);
    const prefix = status.mode === 'site' && status.site ? status.site + ' · ' : '';
    return prefix + t(status.paused ? (status.mode === 'site' ? '⏸ 暂停' : '暂停') : '播放中') + ' ' + time + (duration ? ' / ' + duration : '');
  }
  return status.mode === 'share' ? t(status.sharing ? '电脑正在共享画面' : '电脑还没开始共享画面') : '';
};


