export const formatLive2DActionText = (locale: UiLocale, text: string, params: Record<string, string | number> = {}): string => {
  const template = locale === 'ja-JP' ? LIVE2D_ACTION_JA[text] ?? formatCallStageText(locale, text) : text;
  return template.replace(/\{(\w+)\}/g, (match, key) => Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match);
};
