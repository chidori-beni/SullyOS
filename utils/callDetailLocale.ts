/** Only used on built-in display labels, never on user names or generated text. */
export const formatCallDetailText = (t: (key: UiMessageKey, params?: UiMessageParams) => string, text: string): string => {
  const key = Object.prototype.hasOwnProperty.call(LABELS, text) ? LABELS[text] : undefined;
  return key ? t(key) : text;
};
