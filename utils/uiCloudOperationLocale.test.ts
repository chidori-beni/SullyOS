import { expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import ts from 'typescript';
import { translateUi } from './uiLocale';
const source = readFileSync(resolve(process.cwd(), 'context/OSContext.tsx'), 'utf8');
const body = source.slice(source.indexOf('const cloudBackupToWebDAV ='), source.indexOf('const listCloudBackups ='));
it.each(['zh-CN', 'ja-JP'] as const)('preserves cloud operation progress and data flow in %s', async locale => {
  let state: any = {};
  const states: any[] = [];
  const setState = (value: any) => { state = typeof value === 'function' ? value(state) : value; states.push(state); };
  const blob = new Blob(['fake']);
  const upload = vi.fn(async (_config: unknown, _blob: Blob, _name: string, progress: (pct: number) => void) => { progress(20); return { ok: true }; });
  const download = vi.fn(async (_config: unknown, _file: unknown, progress: (pct: number) => void) => { progress(20); return blob; });
  const cleanup = vi.fn(async (..._args: unknown[]) => {}), exportData = vi.fn(async (..._args: unknown[]) => blob), importData = vi.fn(async (_file: File, _options: { confirmBackendRestore: () => boolean }) => {}), toast = vi.fn(), update = vi.fn(), track = vi.fn();
  const js = ts.transpileModule(body + '\nreturn { cloudBackupToWebDAV, cloudRestoreFromWebDAV };', { compilerOptions: { target: ts.ScriptTarget.ES2020 } }).outputText;
  const fns = new Function('loadBackupProvider', 'setSysOperation', 'cloudBackupConfig', 'exportSystem', 'updateCloudBackupConfig', 'addToast', 'trackEvent', 'importSystem', 'translateUi', 'loadUiLocale', js)(async () => ({ uploadBackup: upload, downloadBackup: download, cleanupOldBackups: cleanup }), setState, { provider: 'github' }, exportData, update, toast, track, importData, translateUi, () => locale);
  await fns.cloudBackupToWebDAV('full');
  expect(exportData).toHaveBeenCalledWith('full', { includeBackendConnection: true });
  expect(states.find(s => s.progress === 59).message).toBe(translateUi(locale, 'settings.cloudOperation.uploadProgress', { pct: 20 }));
  expect(cleanup).toHaveBeenCalledWith({ provider: 'github' }, 5);
  expect(toast).toHaveBeenCalledWith(translateUi(locale, 'settings.cloudOperation.done'), 'success');
  await fns.cloudRestoreFromWebDAV({ name: 'raw{error}.zip' });
  expect(states.find(s => s.progress === 10).message).toBe(translateUi(locale, 'settings.cloudOperation.downloadProgress', { pct: 20 }));
  expect(importData.mock.calls[0][0].name).toBe('raw{error}.zip');
  expect(importData.mock.calls[0][1].confirmBackendRestore()).toBe(true);
  const error = new Error('raw {pct} 🌸');
  download.mockRejectedValueOnce(error);
  await expect(fns.cloudRestoreFromWebDAV({ name: 'fake.zip' })).rejects.toBe(error);
  expect(toast).toHaveBeenCalledWith(translateUi(locale, 'settings.cloudOperation.restoreFailed', { error: error.message }), 'error');
  expect(state).toEqual({ status: 'idle', message: '', progress: 0 });
});
